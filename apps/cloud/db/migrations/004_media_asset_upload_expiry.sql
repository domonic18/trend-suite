-- ============================================================
-- 004 素材直传凭据有效期
--
-- 直传凭据是 HMAC 绑定「素材 + 字节数 + 摘要 + 有效期」，
-- 有效期必须**存在库里**：签发时算一次、校验时再算一次，两边算不出同一个值，
-- 凭据就永远验不过。落列后两边读同一行，天然一致。
--
-- 台账按文件名记账：已应用过的迁移文件不可改内容、不可复用文件名。
-- ============================================================

ALTER TABLE media_assets ADD COLUMN IF NOT EXISTS upload_expires_at timestamptz;
